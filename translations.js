let currentLang = localStorage.getItem('language') || 'ru';

function translatePage() {
    const elements = document.querySelectorAll('[data-translate]');
    elements.forEach(el => {
        const key = el.getAttribute('data-translate');
        const keys = key.split('.');
        let translation = translations[currentLang];
        for (const k of keys) {
            translation = translation?.[k];
        }
        if (translation) {
            if (el.tagName === 'INPUT' && el.type !== 'submit' && el.type !== 'button') {
                el.placeholder = translation;
            } else if (el.tagName === 'BUTTON') {
                // Check if button has a filter-text span inside
                const filterText = el.querySelector('.filter-text');
                if (filterText) {
                    filterText.textContent = translation;
                } else {
                    // If button has child elements (like emoji spans), preserve them
                    const children = Array.from(el.childNodes);
                    const hasNonTextChildren = children.some(child => child.nodeType === 1 && child.tagName !== 'SPAN');
                    if (hasNonTextChildren || children.some(child => child.nodeType === 1 && child.tagName === 'SPAN' && !child.classList.contains('filter-text'))) {
                        // Keep emoji/spans, only update text
                        const textNodes = children.filter(child => child.nodeType === 3);
                        textNodes.forEach(node => node.remove());
                        const lastSpan = el.querySelector('span:last-child');
                        if (lastSpan && lastSpan.classList.contains('filter-text')) {
                            lastSpan.textContent = translation;
                        } else {
                            el.appendChild(document.createTextNode(translation));
                        }
                    } else {
                        el.textContent = translation;
                    }
                }
            } else if (el.tagName === 'INPUT' && (el.type === 'submit' || el.type === 'button')) {
                el.value = translation;
            } else {
                el.textContent = translation;
            }
        }
    });
    
    // Update title attributes
    const titleElements = document.querySelectorAll('[data-translate-title]');
    titleElements.forEach(el => {
        const key = el.getAttribute('data-translate-title');
        const keys = key.split('.');
        let translation = translations[currentLang];
        for (const k of keys) {
            translation = translation?.[k];
        }
        if (translation) {
            el.title = translation;
        }
    });
    
    // Update meta tags
    updateMetaTags();
}

function updateMetaTags() {
    const meta = translations[currentLang]?.meta;
    if (!meta) return;
    
    // Update title
    if (document.title) {
        document.title = meta.title;
    }
    
    // Update description
    let descMeta = document.querySelector('meta[name="description"]');
    if (!descMeta) {
        descMeta = document.createElement('meta');
        descMeta.name = 'description';
        document.head.appendChild(descMeta);
    }
    descMeta.content = meta.description;
    
    // Update keywords
    let keywordsMeta = document.querySelector('meta[name="keywords"]');
    if (!keywordsMeta) {
        keywordsMeta = document.createElement('meta');
        keywordsMeta.name = 'keywords';
        document.head.appendChild(keywordsMeta);
    }
    keywordsMeta.content = meta.keywords;
    
    // Update Open Graph
    let ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.content = meta.title;
    
    let ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.content = meta.description;
    
    // Update HTML lang attribute
    document.documentElement.lang = currentLang;
}

function switchLanguage() {
    currentLang = currentLang === 'kk' ? 'ru' : 'kk';
    localStorage.setItem('language', currentLang);
    translatePage();
    updateLangButton();
}

function updateLangButton() {
    const btn = document.getElementById('langBtn');
    if (btn) {
        btn.textContent = currentLang === 'kk' ? 'Қаз' : 'Рус';
    }
}

// Initialize on page load
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
        translatePage();
        updateLangButton();
    });
} else {
    translatePage();
    updateLangButton();
}

